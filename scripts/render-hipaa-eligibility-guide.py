#!/usr/bin/env python3
"""Render the HIPAA eligibility lists into the developer guide.

    python scripts/render-hipaa-eligibility-guide.py [--check]

Contractors read docs/developer-guide.md and do not have the repository, so
the list of services they may use in a HIPAA tenant's uat and prod has to be
IN the guide. Typed by hand it would drift from the catalog the sweep and the
SCP actually use, and the developer would be told one thing and denied
another. So it is generated, between two markers, from
eligibility/hipaa-eligible-services.tsv.

--check exits non-zero if the guide is out of date, and changes nothing.
scripts/publish-eligibility.sh runs it, so a catalog change cannot reach the
sweep without the guide following.
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "eligibility" / "src"))
import catalog  # noqa: E402

GUIDE = ROOT / "docs" / "developer-guide.md"
CATALOG = ROOT / "eligibility" / "hipaa-eligible-services.tsv"
BEGIN = "<!-- hipaa-eligibility:begin (generated by scripts/render-hipaa-eligibility-guide.py; do not edit) -->"
END = "<!-- hipaa-eligibility:end -->"


def render(version, rows):
    def name(r):
        return catalog.normalise_service(r["service"])

    eligible = sorted((r for r in rows if r["status"] == "eligible"), key=lambda r: name(r).lower())
    carve = sorted((r for r in rows if r["status"] == "carve-out"), key=lambda r: name(r).lower())
    pending = sorted((r for r in rows if r["status"] == "pending"), key=lambda r: name(r).lower())
    denied = sorted((r for r in rows if r["status"] == "not-allowlisted" and r["prefixes"]),
                    key=lambda r: name(r).lower())

    out = [BEGIN, "",
           f"*List version `{version}`, from AWS's HIPAA Eligible Services Reference.*", ""]

    out += ["**Not eligible: use the alternative.** Allowed in dev and test, where the "
            "digest flags it. Denied in uat and prod.", "",
            "| Service | IAM prefix | Use instead |", "|---|---|---|"]
    for r in denied:
        out.append(f"| {name(r)} | `{'`, `'.join(r['prefixes'])}` | {r['alternative'] or '—'} |")
    out.append("")

    out += ["**Eligibility being confirmed: blocked in uat and prod until it is.** "
            "Mostly features AWS documents under an eligible service but gives an IAM "
            "prefix of their own. AltDigital has asked AWS about the most likely ones "
            "(Synthetics, Application Signals, RUM, EventBridge Scheduler and Pipes, "
            "OpenSearch Serverless, S3 Express One Zone, S3 Tables). If your design "
            "depends on any of these, tell AltDigital now.", ""]
    with_alt = [r for r in pending if r["alternative"]]
    out += ["| Service | IAM prefix | Confirmed-eligible alternative available today |",
            "|---|---|---|"]
    for r in with_alt:
        out.append(f"| {name(r)} | `{'`, `'.join(r['prefixes'])}` | {r['alternative']} |")
    out += ["", "Also pending, less likely to come up: " + ", ".join(
        f"{name(r)} (`{'`, `'.join(r['prefixes'])}`)" for r in pending if not r["alternative"]) + "."]
    out.append("")

    out += ["**Also allowed: running the account.** These are not on AWS's list, but "
            "they hold no patient data: identity, billing, quotas, support, tagging. "
            "**Never put patient data in a support case or a tag.**", ""]
    out.append(", ".join(f"{name(r)} (`{'`, `'.join(r['prefixes'])}`)" for r in carve))
    out.append("")

    out += ["<details><summary><b>Eligible services</b> — "
            f"{len(eligible)} on AWS's list. A bracketed note is a limit AWS sets on that "
            "service.</summary>", ""]
    for r in eligible:
        out.append(f"- {name(r)}")
    out += ["", "</details>", "", END]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    version, rows = catalog.load(CATALOG)
    block = render(version, rows)
    text = GUIDE.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        print(f"FAIL  {GUIDE.name} has no hipaa-eligibility markers")
        return 1
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    new = head + block + tail
    if new == text:
        print("ok    developer guide is current")
        return 0
    if args.check:
        print("FAIL  developer guide is out of date with the catalog. "
              "Run scripts/render-hipaa-eligibility-guide.py and commit the result.")
        return 1
    GUIDE.write_text(new, encoding="utf-8", newline="\n")
    print("ok    developer guide updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
